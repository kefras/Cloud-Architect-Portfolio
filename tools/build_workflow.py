"""Build readable static pages, one CSS bundle and the coordinated ATS resume."""

from xml.etree.ElementTree import Element, SubElement, ElementTree, indent

from config import ROOT, content
from pages import build_home, build_resume, build_studies, build_project_directory
from resume_pdf import build_pdf
from project_diagrams import build_project_diagrams
from portrait_assets import build_portrait_assets


def build_styles():
    """Combine ordered CSS sources into one request without minifying them."""
    sources = sorted((ROOT / "css").glob("*.css"))
    banner = "/* Generated by tools/build.py. Edit css/*.css, then rebuild. */\n"
    sections = [path.read_text(encoding="utf-8").strip() for path in sources]
    (ROOT / "styles.css").write_text(
        banner + "\n\n".join(sections) + "\n", encoding="utf-8"
    )


def build_sitemap():
    """Keep discoverable URLs synchronized with configured project pages."""
    root = Element("urlset", xmlns="http://www.sitemaps.org/schemas/sitemap/0.9")
    paths = ["", "resume.html", "projects.html"]
    paths.extend(
        f"case-studies/{project['id']}.html" for project in content["projects"]
    )
    for path in paths:
        SubElement(SubElement(root, "url"), "loc").text = f"https://kefas.live/{path}"
    indent(root)
    ElementTree(root).write(
        ROOT / "sitemap.xml", encoding="utf-8", xml_declaration=True
    )


def main():
    """Keep the build order explicit and the orchestration easy to follow."""
    build_styles()
    build_portrait_assets()
    build_project_diagrams()
    build_home()
    build_studies()
    build_project_directory()
    build_resume()
    build_pdf()
    build_sitemap()
    print("Built portfolio, case studies, web/PDF resumes, styles and sitemap.")

"""Small standard-library template renderer; no server framework is required."""

from html.parser import HTMLParser
from string import Template
import re
from config import TEMPLATES


def render_template(name, context):
    """Insert trusted markup and escaped text into an HTML partial.

    Callers escape plain content with components.escape_html. A missing slot
    raises an error during the build instead of publishing incomplete markup.
    """
    source = read_template(name)
    return Template(source).substitute(context)


def read_template(name):
    """Expand shared section includes before substituting content exactly once."""
    source = (TEMPLATES / name).read_text(encoding="utf-8")
    return re.sub(
        r"<!-- include: ([\w/.-]+) -->",
        lambda match: read_template(match.group(1)),
        source,
    )


class ReadableHTML(HTMLParser):
    """Indent block markup while preserving inline text and script contents.

    Inline groups stay together so formatting never turns `kf.` into `kf .`.
    This formatter is for the controlled project templates, not arbitrary HTML.
    """

    VOID_TAGS = {
        "area",
        "base",
        "br",
        "col",
        "embed",
        "hr",
        "img",
        "input",
        "link",
        "meta",
        "param",
        "source",
        "track",
        "wbr",
    }
    INLINE_GROUPS = {
        "p",
        "h1",
        "h2",
        "h3",
        "a",
        "span",
        "button",
        "label",
        "li",
        "strong",
        "small",
        "em",
        "figcaption",
        "title",
        "script",
        "style",
        "textarea",
    }

    def __init__(self):
        super().__init__(convert_charrefs=False)
        self.lines = []
        self.depth = 0
        self.inline_depth = 0
        self.buffer = ""

    def emit(self, text):
        self.lines.append("  " * self.depth + text)

    def handle_decl(self, decl):
        self.emit(f"<!{decl}>")

    def handle_starttag(self, tag, attrs):
        raw = self.get_starttag_text()
        if self.inline_depth:
            self.buffer += raw
            if tag not in self.VOID_TAGS:
                self.inline_depth += 1
        elif tag in self.INLINE_GROUPS:
            self.buffer = raw
            self.inline_depth = 1
        else:
            self.emit(raw)
            if tag not in self.VOID_TAGS:
                self.depth += 1

    def handle_endtag(self, tag):
        if self.inline_depth:
            self.buffer += f"</{tag}>"
            self.inline_depth -= 1
            if not self.inline_depth:
                self.emit(self.buffer)
                self.buffer = ""
        else:
            self.depth = max(0, self.depth - 1)
            self.emit(f"</{tag}>")

    def handle_data(self, text):
        if self.inline_depth:
            self.buffer += text
        elif text.strip():
            self.emit(text.strip())

    def handle_entityref(self, name):
        self.handle_data(f"&{name};")

    def handle_charref(self, name):
        self.handle_data(f"&#{name};")

    def handle_comment(self, text):
        if self.inline_depth:
            self.buffer += f"<!--{text}-->"
        else:
            self.emit(f"<!--{text}-->")


def format_html(markup):
    """Return readable UTF-8 HTML without changing inline text."""
    formatter = ReadableHTML()
    formatter.feed(markup)
    formatter.close()
    return "\n".join(formatter.lines) + "\n"


def write_html(path, markup):
    """Write a generated page with a pointer to its editable source."""
    notice = "<!-- Generated by tools/build.py. Edit templates/ and content.json. -->\n"
    path.write_text(notice + format_html(markup), encoding="utf-8")
